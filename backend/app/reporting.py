"""Report rendering — markdown, HTML, PDF."""
from __future__ import annotations
import io
import json
from jinja2 import Template
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors

MD_TMPL = Template("""# {{ inv.name }}

**Status:** {{ inv.status }}  •  **Created:** {{ inv.created_at }}  •  **Updated:** {{ inv.updated_at }}

{{ inv.description or "_no description_" }}

## Subjects
{% for s in subjects %}- `{{ s.type }}` **{{ s.value }}** — {{ s.note }}
{% endfor %}

## Collection summary
{% for j in jobs %}- `{{ j.module }}` — {{ j.status }}{% if j.error %} ({{ j.error }}){% endif %} — findings: {{ j.result.get('findings', 0) }}, entities: {{ j.result.get('entities', 0) }}
{% endfor %}

## Entities ({{ entities|length }})
{% for e in entities %}- `{{ e.type }}` **{{ e.value }}** (confidence {{ '%.2f'|format(e.confidence) }})
{% endfor %}

## Relationships ({{ relationships|length }})
{% for r in relationships %}- {{ r.type }} via `{{ r.source }}` — conf {{ '%.2f'|format(r.confidence) }}
{% endfor %}

## Findings ({{ findings|length }})
{% for f in findings %}### {{ f.module }} / {{ f.source }} — {{ f.kind }}
_conf {{ '%.2f'|format(f.confidence) }} • {{ f.collected_at }}_
```json
{{ f.data | tojson(indent=2) }}
```
{% endfor %}

---
*Generated by base — OSINT platform. Evidence provenance preserved per finding.*
""")


def render_markdown(bundle: dict) -> str:
    return MD_TMPL.render(
        inv=bundle["investigation"], subjects=bundle["subjects"], jobs=bundle["jobs"],
        entities=bundle["entities"], relationships=bundle["relationships"],
        findings=bundle["findings"],
    )


def render_html(bundle: dict) -> str:
    md = render_markdown(bundle)
    html = (
        "<!doctype html><meta charset=utf-8>"
        "<title>base report — " + bundle["investigation"]["name"] + "</title>"
        "<style>body{font-family:ui-monospace,Menlo,Consolas,monospace;background:#0f1115;"
        "color:#d9dde3;padding:2rem;max-width:960px;margin:auto;line-height:1.5}"
        "pre{background:#171a21;padding:1rem;overflow:auto;border:1px solid #242933;border-radius:6px}"
        "h1,h2,h3{color:#e8ecf3}code{color:#9ecaff}</style>"
        "<pre>" + md.replace("<", "&lt;") + "</pre>"
    )
    return html


def render_pdf(bundle: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=bundle["investigation"]["name"])
    styles = getSampleStyleSheet()
    story = [Paragraph(bundle["investigation"]["name"], styles["Title"]), Spacer(1, 12)]
    story.append(Paragraph(f"Status: {bundle['investigation']['status']}", styles["Normal"]))
    story.append(Paragraph(bundle["investigation"]["description"] or "no description", styles["Normal"]))
    story.append(Spacer(1, 12))

    story.append(Paragraph("Subjects", styles["Heading2"]))
    for s in bundle["subjects"]:
        story.append(Paragraph(f"[{s['type']}] <b>{s['value']}</b> — {s['note']}", styles["Normal"]))
    story.append(Spacer(1, 12))

    story.append(Paragraph("Jobs", styles["Heading2"]))
    rows = [["Module", "Status", "Findings", "Entities"]]
    for j in bundle["jobs"]:
        rows.append([j["module"], j["status"], j["result"].get("findings", 0), j["result"].get("entities", 0)])
    t = Table(rows, hAlign="LEFT")
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
                           ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
    story.append(t); story.append(Spacer(1, 12))

    story.append(Paragraph(f"Findings ({len(bundle['findings'])})", styles["Heading2"]))
    for f in bundle["findings"][:200]:
        story.append(Paragraph(f"<b>{f['module']} / {f['source']}</b> — {f['kind']} — conf {f['confidence']:.2f}", styles["Normal"]))
        data = json.dumps(f["data"], ensure_ascii=False)[:800]
        story.append(Paragraph(f"<font face='Courier' size=8>{data}</font>", styles["Normal"]))
        story.append(Spacer(1, 6))

    doc.build(story)
    return buf.getvalue()
